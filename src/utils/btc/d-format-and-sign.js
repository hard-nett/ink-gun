import bitcoin from "bitcoinjs-lib";
import { getMetadataFilePath } from "./b-select-metadata";
import fs from "fs";
import { inscribeOrdinal } from "./e-inscribe";

// create signature with payload
function createSignature(message) {
    // private key 
    const seed = bitcoin.Mnemonic.toSeed(process.env.PUBLISHER_MNEMONIC);
    const root = bitcoin.HDPrivateKey.fromSeed(seed, 'mainnet');
    const privateKey = root.derive("m/0'/0/0").privateKey;

    const keyPair = bitcoin.ECPair.fromPrivateKey(privateKey, { network: bitcoin.networks.bitcoin });
    const signature = bitcoin.message.sign(keyPair, message);
    return signature.toString('base64');
}

// need to add to metadata:
// `col` -  collection id via current output ()
// `iid` - inscription id 
// `sig` - the string generated by publisher with the payload of COLLECTION_ID INSCRIPTION_ID NONCE
function signInscriptionMetadata(metadataId, minterAddr) {
    const payload = `${process.env.COLLECTION_ID} ${process.env.INSCRIPTION_ID} ${metadataId}`
    let signature;
    try {
        signature = createSignature(payload);
    } catch (err) {
        console.error('Error defining signature:', err);
        return;
    }

    let fileData;
    try {
        fileData = fs.readFileSync(getMetadataFilePath(metadataId), 'utf-8');
    } catch (err) {
        console.error('Error reading metadata JSON file:', err);
        return;
    }

    if (fileData) {
        let jsonData;
        try {
            jsonData = JSON.parse(fileData);
        } catch (err) {
            console.error('Error parsing JSON file:', err);
            return;
        }

        if (jsonData && signature) {
            jsonData.sig = signature;
            jsonData.col = process.env.COLLECTION_ID;
            jsonData.iid = process.env.INSCRIPTION_ID + '-' + metadataId;
            const newFilePath = getNewMetadataFilePath(metadataId);
            try {
                fs.writeFileSync(newFilePath, JSON.stringify(jsonData, null, 2));
                console.log('Metadata updated successfully. New file:', newFilePath);

                inscribeOrdinal(newFilePath)
            } catch (err) {
                console.error('Error writing metadata JSON file:', err);
            }

        }
    }
}

function getNewMetadataFilePath(metadataId) {
    const newFileName = `${metadataId}.json`;
    const newPath = `../../../metadata_consumed`;
    return newPath;
}

